-- Teach Me a Lesson CMS schema (MySQL 8+)
-- Run once in a dedicated Teach Me a Lesson database after backing up existing data.
CREATE TABLE IF NOT EXISTS tml_subjects (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL UNIQUE,
 slug VARCHAR(140) NOT NULL UNIQUE,
 description TEXT NULL,
 sort_order INT NOT NULL DEFAULT 0,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tml_resource_types (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL UNIQUE,
 slug VARCHAR(140) NOT NULL UNIQUE,
 sort_order INT NOT NULL DEFAULT 0,
 enabled BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tml_key_stages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL UNIQUE,
 slug VARCHAR(140) NOT NULL UNIQUE,
 sort_order INT NOT NULL DEFAULT 0,
 enabled BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tml_year_groups (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL UNIQUE,
 slug VARCHAR(140) NOT NULL UNIQUE,
 key_stage_id BIGINT UNSIGNED NULL,
 sort_order INT NOT NULL DEFAULT 0,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 FOREIGN KEY (key_stage_id) REFERENCES tml_key_stages(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tml_categories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 slug VARCHAR(140) NOT NULL UNIQUE,
 parent_id BIGINT UNSIGNED NULL,
 sort_order INT NOT NULL DEFAULT 0,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 FOREIGN KEY (parent_id) REFERENCES tml_categories(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tml_media (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 original_name VARCHAR(255) NOT NULL,
 storage_key VARCHAR(512) NOT NULL UNIQUE,
 mime_type VARCHAR(120) NOT NULL,
 size_bytes BIGINT UNSIGNED NOT NULL,
 sha256 CHAR(64) NULL,
 alt_text VARCHAR(255) NULL,
 uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tml_resources (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(200) NOT NULL,
 slug VARCHAR(220) NOT NULL UNIQUE,
 summary TEXT NULL,
 body LONGTEXT NULL,
 subject_id BIGINT UNSIGNED NULL,
 resource_type_id BIGINT UNSIGNED NULL,
 category_id BIGINT UNSIGNED NULL,
 primary_media_id BIGINT UNSIGNED NULL,
 thumbnail_media_id BIGINT UNSIGNED NULL,
 external_url VARCHAR(2048) NULL,
 status ENUM('draft','published','archived') NOT NULL DEFAULT 'draft',
 featured BOOLEAN NOT NULL DEFAULT FALSE,
 sort_order INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 published_at TIMESTAMP NULL,
 FOREIGN KEY (subject_id) REFERENCES tml_subjects(id) ON DELETE SET NULL,
 FOREIGN KEY (resource_type_id) REFERENCES tml_resource_types(id) ON DELETE SET NULL,
 FOREIGN KEY (category_id) REFERENCES tml_categories(id) ON DELETE SET NULL,
 FOREIGN KEY (primary_media_id) REFERENCES tml_media(id) ON DELETE SET NULL,
 FOREIGN KEY (thumbnail_media_id) REFERENCES tml_media(id) ON DELETE SET NULL,
 INDEX idx_public_resources (status, published_at),
 INDEX idx_subject (subject_id),
 INDEX idx_type (resource_type_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tml_resource_stages (
 resource_id BIGINT UNSIGNED NOT NULL,
 stage_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(resource_id,stage_id),
 FOREIGN KEY (resource_id) REFERENCES tml_resources(id) ON DELETE CASCADE,
 FOREIGN KEY (stage_id) REFERENCES tml_key_stages(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tml_resource_years (
 resource_id BIGINT UNSIGNED NOT NULL,
 year_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(resource_id,year_id),
 FOREIGN KEY (resource_id) REFERENCES tml_resources(id) ON DELETE CASCADE,
 FOREIGN KEY (year_id) REFERENCES tml_year_groups(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tml_site_settings (
 setting_key VARCHAR(120) PRIMARY KEY,
 setting_value JSON NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
