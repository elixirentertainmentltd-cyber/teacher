-- Teach Me a Lesson · Word Detective classroom word banks
CREATE TABLE IF NOT EXISTS tml_word_banks (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(120) NOT NULL,
  subject VARCHAR(80) NOT NULL,
  stage VARCHAR(3) NOT NULL,
  year_group VARCHAR(24) NOT NULL DEFAULT '',
  published TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_word_banks_public (published,stage)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS tml_word_bank_cases (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  bank_id BIGINT UNSIGNED NOT NULL,
  word VARCHAR(12) NOT NULL,
  clue VARCHAR(300) NOT NULL,
  example VARCHAR(300) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY unique_case (bank_id,word),
  CONSTRAINT fk_word_case_bank FOREIGN KEY (bank_id) REFERENCES tml_word_banks(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
